#!/usr/bin/env python3
"""Render the raw bombardier + resource samples into a markdown report."""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RAW = os.path.join(ROOT, "results", "raw")
APPS = [("go", "Go (chi+pgx+sqlc, native)"),
        ("dotnet", ".NET (Minimal API+Npgsql, Native AOT)")]
SCENARIOS = [
    ("health", "GET /health (no DB)"),
    ("read_one", "GET /users/{id}"),
    ("list_20", "GET /users?limit=20"),
    ("list_100", "GET /users?limit=100"),
    ("update", "PUT /users/{id}"),
    ("create", "POST /users"),
    ("delete", "DELETE /users/{id}"),
]


def load_bombardier(app, name):
    path = os.path.join(RAW, app, f"{name}.bombardier.json")
    with open(path) as f:
        s = f.read()
    return json.loads(s[s.index("{"):])["result"]


_RES_CACHE = {}


def _windows(app):
    out = {}
    with open(os.path.join(RAW, app, "phases.csv")) as f:
        next(f)
        for line in f:
            line = line.strip()
            if not line:
                continue
            phase, s, e = line.split(",")
            out[phase] = (int(s), int(e))
    return out


def load_res(app, name):
    """avg/max app CPU%, app RSS MiB, and system CPU% over the named phase,
    sliced out of the continuous resources.csv by timestamp."""
    key = (app, name)
    if key in _RES_CACHE:
        return _RES_CACHE[key]
    s, e = _windows(app)[name]
    cpu, rss, sys = [], [], []
    with open(os.path.join(RAW, app, "resources.csv")) as f:
        next(f)
        for line in f:
            parts = line.strip().split(",")
            if len(parts) < 6:
                continue
            epoch = int(parts[0])
            if s <= epoch <= e:
                cpu.append(float(parts[3]))
                rss.append(float(parts[4]))
                sys.append(float(parts[5]))
    avg = lambda xs: round(sum(xs) / len(xs), 2) if xs else 0.0
    res = {
        "samples": len(cpu),
        "cpu_pct_avg": avg(cpu), "cpu_pct_max": round(max(cpu), 2) if cpu else 0.0,
        "rss_mib_avg": avg(rss), "rss_mib_max": round(max(rss), 2) if rss else 0.0,
        "sys_cpu_avg": avg(sys), "sys_cpu_max": round(max(sys), 2) if sys else 0.0,
    }
    _RES_CACHE[key] = res
    return res


def fmt(n, d=1):
    return f"{n:,.{d}f}"


def errors(r):
    return (r.get("req4xx", 0) or 0) + (r.get("req5xx", 0) or 0) + (r.get("others", 0) or 0)


def main():
    out = []
    out.append("# Benchmark Results\n")
    out.append("> Generated by `scripts/summarize.py` from `results/raw/`. "
               "All numbers come from a single run; treat them as indicative, "
               "not precise — re-run for your own hardware.\n")

    out.append("## Environment & configuration\n")
    out.append("| | |")
    out.append("|---|---|")
    out.append("| Host | 4 vCPU, ~15 GiB RAM, Linux 6.18 |")
    out.append("| Database | PostgreSQL 16.13 (shared, local TCP) |")
    out.append("| Go service | Go 1.25 native, chi v5.3.0, pgx v5.10.0 (prepared-stmt cache), sqlc v1.31.1 |")
    out.append("| .NET service | .NET 10.0.301 **Native AOT**, Server GC, Npgsql 9.0.3 raw + auto-prepare |")
    out.append("| CPU budget | both apps pinned to cores 0,1 (2 cores); bombardier on cores 2,3 |")
    out.append("| Pool | 10 min / 50 max connections (both) |")
    out.append("| Load | 256 connections, 120 s per scenario, sequential runs |")
    out.append("| Seed | 10,000 rows, reset before each app |")
    out.append("| Recording | continuous 1 s samples of app+system CPU and app RSS for the whole run |")
    out.append("")

    # Auto headline: geometric mean of throughput across DB-backed scenarios
    db_scn = ["read_one", "list_20", "list_100", "create"]
    def geomean(app):
        prod = 1.0
        for s in db_scn:
            prod *= load_bombardier(app, s)["rps"]["mean"]
        return prod ** (1.0 / len(db_scn))
    gg, gn = geomean("go"), geomean("dotnet")
    leader = "Go" if gg > gn else ".NET"
    out.append(f"**Headline (geomean of DB-backed CRUD throughput, excl. the "
               f"lock-bound update):** Go {gg:,.0f} rps vs .NET {gn:,.0f} rps "
               f"— **{leader}** leads by {max(gg,gn)/min(gg,gn):.2f}x. "
               f"Idle memory: Go ~{load_res('go','idle')['rss_mib_avg']:.0f} MiB "
               f"vs .NET ~{load_res('dotnet','idle')['rss_mib_avg']:.0f} MiB.\n")

    # Idle resources
    out.append("### Idle resource usage (server running, zero traffic)\n")
    out.append("| App | CPU % (avg / max) | RSS MiB (avg / max) |")
    out.append("|---|---|---|")
    for app, label in APPS:
        r = load_res(app, "idle")
        out.append(f"| {label} | {r['cpu_pct_avg']} / {r['cpu_pct_max']} | "
                   f"{r['rss_mib_avg']} / {r['rss_mib_max']} |")
    out.append("")

    # Throughput table
    out.append("### Throughput (requests/sec, higher is better)\n")
    out.append("| Scenario | Go RPS | .NET RPS | Winner | Δ |")
    out.append("|---|---:|---:|---|---:|")
    for name, label in SCENARIOS:
        g = load_bombardier("go", name)["rps"]["mean"]
        n = load_bombardier("dotnet", name)["rps"]["mean"]
        win = "Go" if g > n else ".NET"
        ratio = (max(g, n) / min(g, n)) if min(g, n) > 0 else float("inf")
        out.append(f"| {label} | {fmt(g)} | {fmt(n)} | **{win}** | {ratio:.2f}x |")
    out.append("")

    # Latency table
    out.append("### Latency (ms, lower is better)\n")
    out.append("| Scenario | Go avg | Go p99 | .NET avg | .NET p99 |")
    out.append("|---|---:|---:|---:|---:|")
    for name, label in SCENARIOS:
        gr = load_bombardier("go", name)
        nr = load_bombardier("dotnet", name)
        gp = gr["latency"].get("percentiles", {}).get("99", 0) / 1000
        npc = nr["latency"].get("percentiles", {}).get("99", 0) / 1000
        out.append(f"| {label} | {gr['latency']['mean']/1000:.3f} | {gp:.3f} | "
                   f"{nr['latency']['mean']/1000:.3f} | {npc:.3f} |")
    out.append("")

    # Resource-under-load table (CPU% is relative to one core; max 200% here).
    out.append("### Resource usage under load (per scenario)\n")
    out.append("App CPU% is relative to a single core (200% = both pinned cores "
               "saturated). System CPU% is whole-machine (all 4 cores incl. "
               "Postgres + bombardier). Full 1 s time-series in "
               "`results/raw/<app>/resources.csv`.\n")
    out.append("| Scenario | Go app CPU% avg/max | Go RSS MiB avg/max | Go sys% avg "
               "| .NET app CPU% avg/max | .NET RSS MiB avg/max | .NET sys% avg |")
    out.append("|---|---|---|---:|---|---|---:|")
    for name, label in SCENARIOS:
        g = load_res("go", name)
        n = load_res("dotnet", name)
        out.append(f"| {label} | {g['cpu_pct_avg']}/{g['cpu_pct_max']} | "
                   f"{g['rss_mib_avg']}/{g['rss_mib_max']} | {g['sys_cpu_avg']} | "
                   f"{n['cpu_pct_avg']}/{n['cpu_pct_max']} | "
                   f"{n['rss_mib_avg']}/{n['rss_mib_max']} | {n['sys_cpu_avg']} |")
    out.append("")

    # Error check
    out.append("### Error counts (non-2xx responses)\n")
    out.append("| Scenario | Go errors | .NET errors |")
    out.append("|---|---:|---:|")
    for name, label in SCENARIOS:
        out.append(f"| {label} | {errors(load_bombardier('go', name))} | "
                   f"{errors(load_bombardier('dotnet', name))} |")
    out.append("")

    report = "\n".join(out)
    dest = os.path.join(ROOT, "results", "RESULTS.md")
    with open(dest, "w") as f:
        f.write(report)
    print(report)
    print(f"\nWrote {dest}")


if __name__ == "__main__":
    sys.exit(main())

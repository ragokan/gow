using Npgsql;

namespace BenchApi;

// Minimal, AOT-friendly SQL migration runner (goose analog): each script runs
// once, tracked in a schema_migrations table.
public static class Migrations
{
    private static readonly (string Version, string Sql)[] All =
    [
        ("001_init", """
            CREATE TABLE IF NOT EXISTS users (
                id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name       TEXT        NOT NULL,
                email      TEXT        NOT NULL,
                age        INT         NOT NULL,
                created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
                updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
            );
            CREATE INDEX IF NOT EXISTS idx_users_email ON users (email);
        """),
    ];

    public static async Task RunAsync(NpgsqlDataSource db)
    {
        await using var conn = await db.OpenConnectionAsync();

        await using (var cmd = new NpgsqlCommand(
            "CREATE TABLE IF NOT EXISTS schema_migrations (version TEXT PRIMARY KEY, applied_at TIMESTAMPTZ NOT NULL DEFAULT now())",
            conn))
        {
            await cmd.ExecuteNonQueryAsync();
        }

        foreach (var (version, sql) in All)
        {
            await using (var check = new NpgsqlCommand("SELECT 1 FROM schema_migrations WHERE version = $1", conn))
            {
                check.Parameters.AddWithValue(version);
                if (await check.ExecuteScalarAsync() is not null)
                    continue;
            }

            await using var tx = await conn.BeginTransactionAsync();
            await using (var apply = new NpgsqlCommand(sql, conn, tx))
                await apply.ExecuteNonQueryAsync();
            await using (var mark = new NpgsqlCommand("INSERT INTO schema_migrations (version) VALUES ($1)", conn, tx))
            {
                mark.Parameters.AddWithValue(version);
                await mark.ExecuteNonQueryAsync();
            }
            await tx.CommitAsync();
        }
    }
}
